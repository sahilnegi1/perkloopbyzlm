def make_table(header, rows, ratios, caption=None, zebra=True, col_styles=None):
    col_w = [r * AVAIL_W for r in ratios]
    data = [[Paragraph(f'<b>{c}</b>', S['th']) for c in header]]
    for row in rows:
        cells = []
        for i, c in enumerate(row):
            st = S['td'] if not col_styles else S[col_styles[i]]
            cells.append(Paragraph(str(c), st))
        data.append(cells)
    t = Table(data, colWidths=col_w, hAlign='CENTER', repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('GRID', (0, 0), (-1, -1), 0.4, BORDER),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    if zebra:
        for i in range(1, len(data)):
            style.append(('BACKGROUND', (0, i), (-1, i),
                          TABLE_ROW_ODD if i % 2 == 0 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    out = [Spacer(1, 12), t]
    if caption:
        out += [Spacer(1, 4), Paragraph(caption, S['caption'])]
    out.append(Spacer(1, 12))
    return out


def stat_band(stats):
    """Data-sculpture band: [(value, label), ...] — one row of stat cards."""
    cells_top = [Paragraph(v, S['stat']) for v, _ in stats]
    cells_bot = [Paragraph(l, S['statlbl']) for _, l in stats]
    w = AVAIL_W / len(stats)
    t = Table([cells_top, cells_bot], colWidths=[w] * len(stats), hAlign='CENTER')
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), CARD_BG),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, 0), 12),
        ('BOTTOMPADDING', (0, 1), (-1, 1), 12),
        ('TOPPADDING', (0, 1), (-1, 1), 2),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 2),
        ('LINEBELOW', (0, -1), (-1, -1), 1, HEADER_FILL),
    ]))
    return [Spacer(1, 6), t, Spacer(1, 14)]


