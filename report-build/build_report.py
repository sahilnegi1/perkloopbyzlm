class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            self.notify('TOCEntry', (level, text, self.page, key))

    def afterPage(self):
        c = self.canv
        c.saveState()
        c.setStrokeColor(BORDER)
        c.setLineWidth(0.5)
        c.line(LM, BM - 18, PAGE_W - RM, BM - 18)
        c.setFont('FreeSerif', 8)
        c.setFillColor(TEXT_MUTED)
        c.drawString(LM, BM - 30, 'Reward Jar — Production Audit Remediation Report · Round 2')
        c.drawRightString(PAGE_W - RM, BM - 30, f'Page {self.page}')
        c.restoreState()


def add_heading(text, style, level=0):
    key = 'h_' + hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph(f'<a name="{key}"/><b>{text}</b>', style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def safe_keep_together(elements):
    total_h = 0
    for el in elements:
        w, h = el.wrap(AVAIL_W, PAGE_H)
        total_h += h
    if total_h <= MAX_KEEP:
        return [KeepTogether(elements)]
    elif len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    return list(elements)


